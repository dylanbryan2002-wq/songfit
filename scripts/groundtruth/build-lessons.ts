/* Turn the study output into the engine's lessons file (docs/review/27 v3).
     pnpm local scripts/groundtruth/build-lessons.ts [--home ~/Songfit-groundtruth]
   Reads catalog/study.json and writes src/engine/candidates/creatorLessons.data.ts: the playbook (all rules) and the
   lessons the study was confident about (high or medium). Low-confidence lessons (recordings the model does not know)
   are left out as examples: nothing it could not check is taught. Clip ids stay out of the engine file. */
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { parseArgs } from "node:util";

type StudyLesson = { n: number; job: string; video: string; song: string; what_music_does: string; why_it_works: string; lazy_wrong_pick: string; rule: string; confidence: string };
type Study = { prompt_version: string; model: string; lessons: StudyLesson[]; playbook: { rule: string; examples: number[] }[] };

async function main() {
  const { values: args } = parseArgs({ options: { home: { type: "string" } } });
  const home = path.resolve((args.home ?? "~/Songfit-groundtruth").replace(/^~(?=$|\/)/, os.homedir()));
  const study = JSON.parse(await fs.readFile(path.join(home, "catalog", "study.json"), "utf8")) as Study;
  const kept = study.lessons.filter((l) => l.confidence === "high" || l.confidence === "medium");
  const data = {
    version: `${study.prompt_version}/${study.model}/${kept.length}of${study.lessons.length}`,
    playbook: study.playbook.map((r) => r.rule),
    lessons: kept.map((l) => ({ job: l.job, video: l.video, song: l.song, what_music_does: l.what_music_does, why_it_works: l.why_it_works, lazy_wrong_pick: l.lazy_wrong_pick, rule: l.rule })),
  };
  const out = path.resolve(__dirname, "../../src/engine/candidates/creatorLessons.data.ts");
  await fs.writeFile(out, `// GENERATED by scripts/groundtruth/build-lessons.ts from ~/Songfit-groundtruth/catalog/study.json. Do not edit by hand.\n` +
    `// Practice (tune) Reels only; song identity from the audio fingerprint; descriptions corrected by the study pass.\n` +
    `export const LESSONS_DATA = ${JSON.stringify(data, null, 1)} as const;\n`);
  console.log(`wrote ${out}: ${data.playbook.length} rules, ${data.lessons.length} lessons kept of ${study.lessons.length}`);
}

if (require.main === module) main().catch((e) => { console.error(e); process.exit(1); });
